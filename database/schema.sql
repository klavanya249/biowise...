-- BIOWISE AI database schema
create table if not exists public.estimations (
  id bigint generated by default as identity primary key,
  feedstock_type text not null check (feedstock_type in ('cattle_dung','food_waste','agri_residue','mixed')),
  feedstock_quantity_kg numeric(12,2) not null check (feedstock_quantity_kg > 0),
  moisture_percent numeric(5,2) not null check (moisture_percent between 0 and 100),
  retention_days integer not null check (retention_days between 1 and 180),
  temperature_c numeric(5,2) not null check (temperature_c between 0 and 100),
  ph numeric(4,2) not null check (ph between 0 and 14),
  organic_load numeric(6,2) not null check (organic_load between 0 and 20),
  gas_pressure_kpa numeric(7,2) check (gas_pressure_kpa between 0 and 1000),
  base_potential_m3_day numeric(12,3) not null check (base_potential_m3_day >= 0),
  condition_factor numeric(7,3) not null check (condition_factor >= 0),
  estimated_gas_m3_day numeric(12,3) not null check (estimated_gas_m3_day >= 0),
  status text not null check (status in ('Normal','Warning','Critical')),
  recommendations text[] not null default '{}',
  created_at timestamptz not null default now()
);

create index if not exists estimations_created_at_idx
  on public.estimations (created_at desc);

-- The application uses the Supabase service-role key only inside the Express server.
-- Keep this table inaccessible to browser/anon clients. Do not add public RLS policies.
alter table public.estimations enable row level security;
